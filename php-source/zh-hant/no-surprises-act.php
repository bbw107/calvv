                            定額自付、共同保險與自付額。您的保險計畫將直接向網路外醫療人員與機構付款。</li>
                        <li>對於急診服務，或在網路內機構接受的特定網路外服務，您所支付的金額通常必須計入
                            您的網路內自付額與自付上限。</li>
