                    <div class="heading block_heading">
                        <h2 class="h4 textColor_Blue">What Is &ldquo;Balance Billing&rdquo;?</h2>
                    </div>
                    <p>When you see a physician or other health care provider, you may owe certain out-of-pocket costs,
                        such as a copayment, coinsurance or deductible. You may owe additional costs, or the full cost of
                        a service, if you see a provider or visit a facility that is not in your health plan's network.</p>
                    <p>&ldquo;Out-of-network&rdquo; means providers and facilities that have not signed a contract with
                        your health plan. Out-of-network providers may be permitted to bill you for the difference
                        between what your plan agreed to pay and the full amount charged for a service. This is called
                        &ldquo;balance billing.&rdquo; This amount is likely more than in-network costs for the same
                        service, and might not count toward your plan's annual out-of-pocket limit.</p>

                    <div class="heading block_heading">
                        <h2 class="h4 textColor_Blue">You Are Protected From Balance Billing For</h2>
                    </div>

                    <div class="heading block_heading">
                        <h3 class="h6 textColor_Blue">Emergency Services</h3>
                    </div>
                    <p>If you have an emergency medical condition and receive emergency services from an out-of-network
                        provider or facility, the most that provider or facility may bill you is your plan's in-network
                        cost-sharing amount, such as copayments and coinsurance. You cannot be balance billed for these
                        emergency services, including services you may receive after you are in stable condition, unless
                        you give written consent and give up your protections not to be balance billed for those
                        post-stabilization services.</p>

                    <div class="heading block_heading">
                        <h3 class="h6 textColor_Blue">Certain Services at an In-Network Facility</h3>
                    </div>
                    <p>When you receive services from an in-network hospital or ambulatory surgical center, certain
                        providers there may be out-of-network. In these cases, the most those providers may bill you is
                        your plan's in-network cost-sharing amount. This applies to services such as anaesthesiology,
                        pathology, radiology and laboratory services, and applies to certain other providers if you did
                        not have the ability to choose an in-network provider.</p>

                    <p>When balance billing is not allowed, you also have the following protections:</p>
                    <ul class="arrow_list">
                        <li>You are only responsible for paying your share of the cost &mdash; the copayments,
                            coinsurance and deductibles that you would pay if the provider or facility were in-network.
                            Your health plan will pay out-of-network providers and facilities directly.</li>
                        <li>Your health plan generally must count any amount you pay for emergency services, or for
                            certain out-of-network services at an in-network facility, toward your in-network deductible
                            and out-of-pocket limit.</li>
                        <li>You should never be asked to give up your protections from balance billing.</li>
                    </ul>

                    <div class="heading block_heading">
                        <h2 class="h4 textColor_Blue">Your Right to a Good Faith Estimate</h2>
                    </div>
                    <p>If you don't have insurance, or you are not planning to submit a claim to your insurance for a
                        service, you have a right to receive a &ldquo;Good Faith Estimate&rdquo; explaining how much your
                        care will cost.</p>
                    <ul class="arrow_list">
                        <li>You have the right to receive a Good Faith Estimate for the total expected cost of any
                            non-emergency items or services, including related costs such as medical tests, prescription
                            drugs, equipment and facility fees, before you schedule an item or service.</li>
                        <li>You can ask us, and any other provider you choose, for a Good Faith Estimate before you
                            schedule an item or service.</li>
                        <li>If you schedule an item or service at least 3 business days in advance, we must give you a
                            Good Faith Estimate in writing within 1 business day after scheduling. If you schedule at
                            least 10 business days in advance, you must receive the estimate within 3 business days of
                            scheduling.</li>
                        <li>If you receive a bill that is at least $400 more than your Good Faith Estimate, you can
                            dispute the bill through the federal patient&ndash;provider dispute resolution process.</li>
                        <li>Be sure to save a copy or a photograph of your Good Faith Estimate.</li>
                    </ul>
                    <p>For questions or more information about your right to a Good Faith Estimate, or how to submit a
