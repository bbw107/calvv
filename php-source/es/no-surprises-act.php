                        <h3 class="h6 textColor_Blue">Servicios de Urgencia</h3>
                    </div>
                    <p>Si tiene una afección médica de urgencia y recibe servicios de urgencia de un proveedor o centro
                        fuera de la red, lo máximo que ese proveedor o centro puede facturarle es el importe de reparto
                        de costes dentro de la red de su plan, como copagos y coseguros. No se le puede aplicar
                        facturación del saldo por estos servicios de urgencia, incluidos los servicios que reciba una
                        vez que esté en condición estable, salvo que dé su consentimiento por escrito y renuncie a sus
                        protecciones para esos servicios posteriores a la estabilización.</p>

                    <div class="heading block_heading">
                        <h3 class="h6 textColor_Blue">Ciertos Servicios en un Centro Dentro de la Red</h3>
                    </div>
                    <p>Cuando recibe servicios en un hospital o centro quirúrgico ambulatorio dentro de la red, algunos
                        proveedores allí pueden estar fuera de la red. En estos casos, lo máximo que esos proveedores
                        pueden facturarle es el importe de reparto de costes dentro de la red de su plan. Esto se aplica
                        a servicios como anestesiología, patología, radiología y análisis de laboratorio, y a otros
                        proveedores si usted no tuvo la posibilidad de elegir un proveedor dentro de la red.</p>

                    <p>Cuando la facturación del saldo no está permitida, usted también tiene las siguientes
                        protecciones:</p>
                    <ul class="arrow_list">
                        <li>Solo es responsable de pagar su parte del coste &mdash; los copagos, coseguros y deducibles
                            que pagaría si el proveedor o centro perteneciera a la red. Su plan de salud pagará
                            directamente a los proveedores y centros fuera de la red.</li>
                        <li>Su plan de salud generalmente debe computar cualquier importe que usted pague por servicios
                            de urgencia, o por ciertos servicios fuera de la red en un centro dentro de la red, para su
                            deducible y su límite de gastos de bolsillo dentro de la red.</li>
                        <li>Nunca se le debe pedir que renuncie a sus protecciones frente a la facturación del saldo.</li>
                    </ul>

