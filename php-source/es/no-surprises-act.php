                    </div>
                    <p>Cuando acude a un médico u otro profesional sanitario, es posible que deba pagar determinados
                        gastos de su bolsillo, como un copago, un coseguro o un deducible. Puede deber gastos
                        adicionales, o el coste total de un servicio, si acude a un proveedor o centro que no pertenece
                        a la red de su plan de salud.</p>
                    <p>&laquo;Fuera de la red&raquo; significa proveedores y centros que no han firmado un contrato con
                        su plan de salud. A los proveedores fuera de la red se les puede permitir facturarle la
                        diferencia entre lo que su plan acordó pagar y el importe total cobrado por un servicio. Esto se
                        denomina &laquo;facturación del saldo&raquo;. Este importe suele ser mayor que el coste dentro
                        de la red por el mismo servicio y puede no computar para el límite anual de gastos de su
                        bolsillo de su plan.</p>

