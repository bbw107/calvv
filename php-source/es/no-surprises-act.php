                    </div>
                    <p>Si no tiene seguro, o no piensa presentar una reclamación a su seguro por un servicio, tiene
                        derecho a recibir un &laquo;presupuesto de buena fe&raquo; (Good Faith Estimate) que explique
                        cuánto costará su atención.</p>
                    <ul class="arrow_list">
                        <li>Tiene derecho a recibir un presupuesto de buena fe por el coste total previsto de cualquier
                            artículo o servicio que no sea de urgencia, incluidos costes relacionados como pruebas
                            médicas, medicamentos con receta, equipos y tarifas del centro, antes de programar el
                            artículo o servicio.</li>
                        <li>Puede solicitarnos, y solicitar a cualquier otro proveedor que elija, un presupuesto de
                            buena fe antes de programar un artículo o servicio.</li>
                        <li>Si programa un artículo o servicio con al menos 3 días hábiles de antelación, debemos
                            entregarle un presupuesto de buena fe por escrito en el plazo de 1 día hábil desde la
                            programación. Si lo programa con al menos 10 días hábiles de antelación, debe recibir el
                            presupuesto en el plazo de 3 días hábiles desde la programación.</li>
                        <li>Si recibe una factura que supera en al menos 400 dólares su presupuesto de buena fe, puede
                            impugnarla mediante el proceso federal de resolución de disputas entre paciente y
